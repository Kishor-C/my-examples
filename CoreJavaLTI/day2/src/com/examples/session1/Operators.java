package com.examples.session1;

public class Operators {
	public static void main(String[] args) {
		int a = 5;
		int b = 6;
		System.out.println(a | b); // 101 | 110 = 111
		System.out.println(a & b); // 101 & 110 = 100

		System.out.println(a > b || a < b);
		System.out.println(a > b && a < b);
		
	}
}
